function specsForPlan(plan: PaidUpgradePlanId, t: Translations) {
  switch (plan) {
    case 'starter':
      return {
        minutes: '45 min',
        agents: '1',
        documents: t.pricingDocsStarter,
        storage: '100 MB',
        support: t.pricingSupportPriority,
      };
    case 'growth':
      return {
        minutes: '200 min',
        agents: '2',
        documents: t.pricingDocsGrowth,
        storage: '400 MB',
        support: t.pricingSupportPriority,
      };
    case 'scale':
      return {
        minutes: '500 min',
        agents: '5',
        documents: t.pricingDocsScale,
        storage: t.pricingStorageScale,
        support: t.pricingSupportDedicated,
      };
  }
}

export function paidPlanFeatureRows(
  plan: PaidUpgradePlanId,
  t: Translations,
): UpgradePlanFeatureRow[] {
  const s = specsForPlan(plan, t);
  return [
    { text: `${t.pricingFeatureIncludedMinutes}: ${s.minutes}`, icon: ICON_TIME },
    { text: `${t.pricingFeatureAgents}: ${s.agents}`, icon: ICON_AGENTS },
    { text: `${t.pricingFeatureDocuments}: ${s.documents}`, icon: ICON_DOCUMENTS },
    { text: `${t.pricingFeatureStorage}: ${s.storage}`, icon: ICON_STORAGE },
    { text: `${t.pricingFeatureSupport}: ${s.support}`, icon: ICON_SUPPORT },
  ];
}
